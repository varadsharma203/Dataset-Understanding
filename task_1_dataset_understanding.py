import pandas as pd
import numpy as np
import seaborn as sns # We will use seaborn to easily load the Titanic dataset

# 1. Load the dataset
# "Load the dataset using Pandas and display first and last few records"
df = sns.load_dataset('titanic')

print("--- First 5 Rows ---")
display(df.head())
print("\n--- Last 5 Rows ---")
display(df.tail())

# 2. Inspect Data Structure & Types
# "Use df.info() and df.describe()"
print("\n--- Dataset Info (Nulls & Dtypes) ---")
df.info()

print("\n--- Statistical Summary (Numerical) ---")
display(df.describe())

print("\n--- Statistical Summary (Categorical) ---")
# Including 'O' checks object/categorical columns
display(df.describe(include=['O']))

# 3. Analyze Specific Columns
# "Check unique values in categorical columns"
print("\n--- Unique Values in Key Categorical Columns ---")
print(f"Sex: {df['sex'].unique()}")
print(f"Embarked: {df['embarked'].unique()}")
print(f"Class: {df['class'].unique()}")

# 4. Check for Missing Values
# "Identify data quality issues like missing values"
print("\n--- Missing Values Count ---")
print(df.isnull().sum())

# 5. Check Target Variable Balance
# "Analyze dataset size... identify target variable"
# Target is 'survived' (0 = No, 1 = Yes)
print("\n--- Target Variable Distribution (Survived) ---")
print(df['survived'].value_counts())
print(f"\nData Imbalance Ratio: {df['survived'].value_counts(normalize=True)}")